// Hub maintains the set of active clients, orchestrates room broadcasting,
// and manages horizontal synchronization across cluster nodes.
type Hub struct {
	cfg            *config.Config
	nodeID         string
	clients        map[*Client]bool
	sessions       map[string]*Client // maps ClientID and SessionID to Client
	rooms          map[string]*Room
	stateMu        sync.RWMutex
	register       chan *Client
	unregister     chan *Client
	broadcastLocal chan *models.ClusterMessage
	pubsub         redis.PubSubBackend

	// Operational Metrics
	totalSessions atomic.Int64
	messagesIn    atomic.Int64
	messagesOut   atomic.Int64
	startTime     time.Time
}

// NewHub constructs a new thread-safe Connection Hub.
func NewHub(cfg *config.Config, pubsub redis.PubSubBackend) *Hub {
	return &Hub{
		cfg:            cfg,
		nodeID:         cfg.NodeID,
		clients:        make(map[*Client]bool),
		sessions:       make(map[string]*Client),
		rooms:          make(map[string]*Room),
		register:       make(chan *Client, 256),
		unregister:     make(chan *Client, 256),
		broadcastLocal: make(chan *models.ClusterMessage, 1024),
		pubsub:         pubsub,
		startTime:      time.Now(),
	}
}

// RegisterChannel returns the client registration channel.
func (h *Hub) RegisterChannel() chan<- *Client {
	return h.register
}

// UnregisterChannel returns the client unregistration channel.
func (h *Hub) UnregisterChannel() chan<- *Client {
	return h.unregister
}

// Run executes the core concurrent event loop.
func (h *Hub) Run(ctx context.Context) {
	// Subscribe to Redis Pub/Sub cluster events
	if h.pubsub != nil {
		_ = h.pubsub.Subscribe(ctx, func(clusterMsg *models.ClusterMessage) {
			select {
			case h.broadcastLocal <- clusterMsg:
			default:
				logger.Get().Warn("Cluster broadcast queue full; dropped frame",
					slog.String("room", clusterMsg.Room),
					slog.String("trace_id", clusterMsg.TraceID))
			}
		})
	}

	for {
		select {
		case <-ctx.Done():
			h.stateMu.Lock()
			for client := range h.clients {
				client.Close()
			}
			h.stateMu.Unlock()
			logger.Get().Info("Hub event loop shut down cleanly")
			return

		case client := <-h.register:
			h.stateMu.Lock()
			h.clients[client] = true
			h.sessions[client.ID()] = client
			h.sessions[client.SessionID()] = client
			h.totalSessions.Add(1)
			h.stateMu.Unlock()

			logger.Get().Info("Client session registered",
				slog.String("client_id", client.ID()),
				slog.String("session_id", client.SessionID()),
				slog.String("nickname", client.Nickname()),
				slog.String("remote_addr", client.session.RemoteAddr))

			// Send Welcome & Session Handshake
			client.SendJSON(&models.OutboundEnvelope{
				Type:   models.TypeAck,
				Action: "handshake",
				Sender: &models.SenderInfo{
					ID:        client.ID(),
					Nickname:  client.Nickname(),
					SessionID: client.SessionID(),
				},
				Data: map[string]any{
					"message":   "Connected to Fickle WebSocket Hub",
					"node_id":   h.nodeID,
					"client_id": client.ID(),
				},
				TraceID:   uuid.New().String(),
				NodeID:    h.nodeID,
				Timestamp: time.Now().UnixMilli(),
			})

		case client := <-h.unregister:
			h.stateMu.Lock()
			if _, exists := h.clients[client]; exists {
				delete(h.clients, client)
				delete(h.sessions, client.ID())
				delete(h.sessions, client.SessionID())

				// Detach from all rooms
				client.roomsMu.RLock()
				subscribedRooms := make([]string, 0, len(client.rooms))
				for roomName := range client.rooms {
					subscribedRooms = append(subscribedRooms, roomName)
				}
				client.roomsMu.RUnlock()

				for _, roomName := range subscribedRooms {
					if room, ok := h.rooms[roomName]; ok {
						if room.Remove(client) {
							delete(h.rooms, roomName)
						}
					}
				}

				logger.Get().Info("Client session unregistered",
					slog.String("client_id", client.ID()),
					slog.String("session_id", client.SessionID()))
			}
			h.stateMu.Unlock()

		case clusterMsg := <-h.broadcastLocal:
			// If this message was generated by this local node and already delivered locally,
			// avoid echoing it back to local clients
			if clusterMsg.OriginNodeID == h.nodeID {
				continue
			}

			h.deliverLocal(clusterMsg.Room, clusterMsg.Payload, nil)
		}
	}
}

// HandleInbound processes client commands decoded by ReadPump.
func (h *Hub) HandleInbound(ctx context.Context, client *Client, p models.InboundPayload) {
	h.messagesIn.Add(1)
	log := logger.FromContext(ctx)

	switch p.Action {
	case models.ActionJoin:
		if p.Room == "" {
			client.SendJSON(&models.OutboundEnvelope{
				Type:      models.TypeError,
				Action:    "join_room",
				Data:      map[string]string{"error": "Room name required"},
				TraceID:   p.TraceID,
				NodeID:    h.nodeID,
				Timestamp: time.Now().UnixMilli(),
			})
			return
		}
		h.JoinRoom(client, p.Room)
		client.SendJSON(&models.OutboundEnvelope{
			Type:   models.TypeAck,
			Action: "join_room",
			Room:   p.Room,
			Data: map[string]any{
				"status": "joined",
				"room":   p.Room,
			},
			TraceID:   p.TraceID,
			NodeID:    h.nodeID,
			Timestamp: time.Now().UnixMilli(),
		})
		log.Info("Client joined room", slog.String("room", p.Room), slog.String("client_id", client.ID()))

	case models.ActionLeave:
		if p.Room != "" {
			h.LeaveRoom(client, p.Room)
			client.SendJSON(&models.OutboundEnvelope{
				Type:   models.TypeAck,
				Action: "leave_room",
				Room:   p.Room,
				Data: map[string]any{
					"status": "left",
					"room":   p.Room,
				},
				TraceID:   p.TraceID,
				NodeID:    h.nodeID,
				Timestamp: time.Now().UnixMilli(),
			})
			log.Info("Client left room", slog.String("room", p.Room), slog.String("client_id", client.ID()))
		}

	case models.ActionBroadcast:
		if p.Nickname != "" {
			client.SetNickname(p.Nickname)
		}

		envelope := models.OutboundEnvelope{
			Type:   models.TypeMessage,
			Action: models.ActionBroadcast,
			Room:   p.Room,
			Sender: &models.SenderInfo{
				ID:        client.ID(),
				Nickname:  client.Nickname(),
				SessionID: client.SessionID(),
			},
			Data:      p.Data,
			TraceID:   p.TraceID,
			NodeID:    h.nodeID,
			Timestamp: time.Now().UnixMilli(),
		}

		if p.Room != "" {
			if !client.IsSubscribed(p.Room) {
				h.JoinRoom(client, p.Room)
			}
			h.BroadcastToRoom(ctx, p.Room, envelope, nil, true)
		} else {
			h.BroadcastGlobal(ctx, envelope, nil, true)
		}
		log.Info("Broadcast message dispatched",
			slog.String("room", p.Room),
			slog.String("client_id", client.ID()),
			slog.String("trace_id", p.TraceID))

	case models.ActionDirect:
		if p.TargetID == "" {
			client.SendJSON(&models.OutboundEnvelope{
				Type:      models.TypeError,
				Action:    models.ActionDirect,
				Data:      map[string]string{"error": "target_id required"},
				TraceID:   p.TraceID,
				NodeID:    h.nodeID,
				Timestamp: time.Now().UnixMilli(),
			})
			return
		}

		envelope := models.OutboundEnvelope{
			Type:   models.TypeMessage,
			Action: models.ActionDirect,
			Sender: &models.SenderInfo{
				ID:        client.ID(),
				Nickname:  client.Nickname(),
				SessionID: client.SessionID(),
			},
			Data:      p.Data,
			TraceID:   p.TraceID,
			NodeID:    h.nodeID,
			Timestamp: time.Now().UnixMilli(),
		}

		sent := h.SendDirect(p.TargetID, envelope)
		client.SendJSON(&models.OutboundEnvelope{
			Type:   models.TypeAck,
			Action: models.ActionDirect,
			Data: map[string]any{
				"delivered": sent,
				"target_id": p.TargetID,
			},
			TraceID:   p.TraceID,
			NodeID:    h.nodeID,
			Timestamp: time.Now().UnixMilli(),
		})

	case models.ActionPing:
		client.SendJSON(&models.OutboundEnvelope{
			Type:      models.TypeAck,
			Action:    models.ActionPong,
			TraceID:   p.TraceID,
			NodeID:    h.nodeID,
			Timestamp: time.Now().UnixMilli(),
		})

	default:
		log.Warn("Unhandled action received", slog.String("action", p.Action))
	}
}

// JoinRoom binds a client to a room.
func (h *Hub) JoinRoom(c *Client, roomName string) {
	h.stateMu.Lock()
	room, exists := h.rooms[roomName]
	if !exists {
		room = NewRoom(roomName)
		h.rooms[roomName] = room
	}
	h.stateMu.Unlock()

	room.Add(c)
}

// LeaveRoom unbinds a client from a room.
func (h *Hub) LeaveRoom(c *Client, roomName string) {
	h.stateMu.Lock()
	defer h.stateMu.Unlock()

	if room, exists := h.rooms[roomName]; exists {
		if room.Remove(c) {
			delete(h.rooms, roomName)
		}
	}
}

// BroadcastToRoom dispatches a message to local subscribers in a room,
// and optionally syncs across nodes using Redis Pub/Sub.
func (h *Hub) BroadcastToRoom(ctx context.Context, roomName string, envelope models.OutboundEnvelope, skipClient *Client, syncCluster bool) {
	h.deliverLocal(roomName, envelope, skipClient)

	if syncCluster && h.pubsub != nil && h.pubsub.IsConnected() {
		go func() {
			clusterMsg := &models.ClusterMessage{
				OriginNodeID: h.nodeID,
				Room:         roomName,
				Payload:      envelope,
				TraceID:      envelope.TraceID,
				Timestamp:    envelope.Timestamp,
			}
			_ = h.pubsub.Publish(ctx, clusterMsg)
		}()
	}
}

// BroadcastGlobal distributes a message to all connected clients.
func (h *Hub) BroadcastGlobal(ctx context.Context, envelope models.OutboundEnvelope, skipClient *Client, syncCluster bool) {
	h.deliverLocal("", envelope, skipClient)

	if syncCluster && h.pubsub != nil && h.pubsub.IsConnected() {
		go func() {
			clusterMsg := &models.ClusterMessage{
				OriginNodeID: h.nodeID,
				Room:         "",
				Payload:      envelope,
				TraceID:      envelope.TraceID,
				Timestamp:    envelope.Timestamp,
			}
			_ = h.pubsub.Publish(ctx, clusterMsg)
		}()
	}
}

// SendDirect delivers an envelope to a specific target client ID or session ID.
func (h *Hub) SendDirect(targetID string, envelope models.OutboundEnvelope) bool {
	h.stateMu.RLock()
	targetClient, exists := h.sessions[targetID]
	h.stateMu.RUnlock()

	if !exists {
		return false
	}
	sent := targetClient.SendJSON(&envelope)
	if sent {
		h.messagesOut.Add(1)
	}
	return sent
}

func (h *Hub) deliverLocal(roomName string, envelope models.OutboundEnvelope, skipClient *Client) {
	raw, err := json.Marshal(envelope)
	if err != nil {
		return
	}

	if roomName != "" {
		h.stateMu.RLock()
		room, exists := h.rooms[roomName]
		h.stateMu.RUnlock()

		if exists {
			sent := room.Broadcast(raw, skipClient)
			h.messagesOut.Add(int64(sent))
		}
	} else {
		// Global fanout
		h.stateMu.RLock()
		clients := make([]*Client, 0, len(h.clients))
		for c := range h.clients {
			if c != skipClient {
				clients = append(clients, c)
			}
		}
		h.stateMu.RUnlock()

		sentCount := 0
		for _, c := range clients {
			if c.SendRaw(raw) {
				sentCount++
			}
		}
		h.messagesOut.Add(int64(sentCount))
	}
}

// GetMetrics returns a snapshot of server telemetry.
func (h *Hub) GetMetrics() models.ServerMetrics {
	h.stateMu.RLock()
	activeClients := len(h.clients)
	activeRoomsCount := len(h.rooms)
	roomStats := make([]models.RoomInfo, 0, len(h.rooms))
	for name, room := range h.rooms {
		roomStats = append(roomStats, models.RoomInfo{
			Name:        name,
			ClientCount: room.ClientCount(),
		})
	}
	h.stateMu.RUnlock()

	redisConnected := false
	if h.pubsub != nil {
		redisConnected = h.pubsub.IsConnected()
	}

	return models.ServerMetrics{
		NodeID:            h.nodeID,
		UptimeSeconds:     int64(time.Since(h.startTime).Seconds()),
		ActiveConnections: activeClients,
		TotalSessions:     h.totalSessions.Load(),
		ActiveRoomsCount:  activeRoomsCount,
		TotalMessagesIn:   h.messagesIn.Load(),
		TotalMessagesOut:  h.messagesOut.Load(),
		RedisConnected:    redisConnected,
		Rooms:             roomStats,
	}
}

// GetRoomStats returns room membership metrics.
func (h *Hub) GetRoomStats() []models.RoomInfo {
	h.stateMu.RLock()
	defer h.stateMu.RUnlock()

	stats := make([]models.RoomInfo, 0, len(h.rooms))
	for name, room := range h.rooms {
		stats = append(stats, models.RoomInfo{
			Name:        name,
			ClientCount: room.ClientCount(),
		})
	}
	return stats
}

// GetSession retrieves session metadata for a given client ID or session ID.
func (h *Hub) GetSession(id string) (*models.SessionMetadata, bool) {
	h.stateMu.RLock()
	client, exists := h.sessions[id]
	h.stateMu.RUnlock()

	if !exists {
		return nil, false
	}
	return client.session, true
}
